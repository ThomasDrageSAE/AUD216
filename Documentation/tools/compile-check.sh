#!/bin/bash
#
# compile-check.sh — compile the project's C# without opening the Unity editor.
#
# Usage:   bash Documentation/tools/compile-check.sh
# Exit:    0 = both assemblies compile, 1 = errors (printed) or prerequisites missing
#
# Why this exists: this project has no automated tests, and opening the editor is
# the only other way to find out whether an edit compiles. Unity ships its own
# Roslyn compiler and .NET runtime, so we can drive them directly using the
# reference list Unity already generated in Assembly-CSharp*.csproj.
#
# Works on macOS and on Windows under Git Bash (MSYS). Overrides:
#   UNITY_VERSION=6000.0.72f1   pick a different installed editor
#   UNITY_ROOT=<dir>            point at the editor's runtime dir directly
#                               (macOS: …/Unity.app/Contents, Windows: …/Editor/Data)
#
# The .csproj files can be stale (they are regenerated by the editor), so the
# source list is reconciled against what is actually on disk: files listed but
# deleted are skipped, and .cs files present but not yet listed are added.
#
# NOTE: this checks compilation only. It cannot catch scene-wiring breakage —
# serialized field renames, UnityEvent method names, or Editor scripts binding
# properties by string (see WaveManagerExporter). Check those by hand.

set -uo pipefail

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
UNITY_VERSION="${UNITY_VERSION:-6000.0.72f1}"

# ---- platform -----------------------------------------------------------------
case "$(uname -s)" in
  MINGW*|MSYS*|CYGWIN*) ON_WINDOWS=1 ;;
  *)                    ON_WINDOWS=0 ;;
esac

# Native tools (dotnet, csc, python.exe) on Windows do not understand MSYS paths
# like /d/GitHub/…; hand them mixed-form paths (D:/GitHub/…) instead.
topath() {
  if [ "$ON_WINDOWS" = 1 ]; then cygpath -m "$1"; else printf '%s\n' "$1"; fi
}

if [ -n "${UNITY_ROOT:-}" ]; then
  UNITY="$UNITY_ROOT"
elif [ "$ON_WINDOWS" = 1 ]; then
  UNITY="/c/Program Files/Unity/Hub/Editor/${UNITY_VERSION}/Editor/Data"
else
  UNITY="/Applications/Unity/Hub/Editor/${UNITY_VERSION}/Unity.app/Contents"
fi

DOTNET="$UNITY/NetCoreRuntime/dotnet"
[ "$ON_WINDOWS" = 1 ] && DOTNET="$DOTNET.exe"
CSC="$UNITY/DotNetSdkRoslyn/csc.dll"

if [ ! -x "$DOTNET" ] || [ ! -f "$CSC" ]; then
  echo "❌ Unity $UNITY_VERSION not found at $UNITY"
  echo "   Set UNITY_VERSION=<version> or UNITY_ROOT=<dir> to point at a different install."
  exit 1
fi

# ---- python -------------------------------------------------------------------
# On Windows the bare name `python3` is usually the Microsoft Store stub, which
# prints an install hint and exits non-zero — so probe each candidate for real.
PY=""
for cand in "py -3" python3 python; do
  if $cand -c "import sys; sys.exit(0 if sys.version_info >= (3, 6) else 1)" >/dev/null 2>&1; then
    PY="$cand"; break
  fi
done
if [ -z "$PY" ]; then
  echo "❌ No Python 3 found (tried: py -3, python3, python)."
  exit 1
fi

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# ---- build the csc response file from a .csproj -------------------------------
build_rsp() {
$PY - "$(topath "$PROJECT_DIR")" "$1" "$(topath "$2")" <<'PY'
import re, os, sys
proj_dir, csproj, out_rsp = sys.argv[1], sys.argv[2], sys.argv[3]
text = open(os.path.join(proj_dir, csproj), encoding="utf-8").read()

sources = [s.replace('\\', '/') for s in re.findall(r'<Compile Include="([^"]+)"', text)]
refs = re.findall(r'<HintPath>([^<]+)</HintPath>', text)
defines = re.search(r'<DefineConstants>([^<]*)</DefineConstants>', text).group(1)
editor_asm = 'Editor' in csproj

src_ok = [os.path.join(proj_dir, s) for s in sources if os.path.exists(os.path.join(proj_dir, s))]

def resolve(r):
    r = r.replace('\\', '/')
    for cand in (r, os.path.join(proj_dir, r)):
        if os.path.exists(cand):
            return cand
    return None
ref_ok = [p for p in (resolve(r) for r in refs) if p]

# Pick up .cs files not in the (possibly stale) .csproj list.
#
# The editor assembly is compiled together with the runtime sources rather than
# referencing a built Assembly-CSharp.dll, so for it we add every .cs we don't
# already have. For the runtime assembly we add non-Editor files only.
extra = []
known = set(os.path.normpath(p).casefold() for p in src_ok)
for root, dirs, files in os.walk(os.path.join(proj_dir, "Assets")):
    in_editor_dir = (os.sep + "Editor" + os.sep) in root + os.sep
    if in_editor_dir and not editor_asm:
        continue
    for f in files:
        if not f.endswith(".cs"):
            continue
        p = os.path.join(root, f)
        if os.path.normpath(p).casefold() not in known:
            extra.append(p)

lines = ["-target:library", "-out:" + os.path.join(os.path.dirname(out_rsp), "out.dll"),
         "-langversion:9.0", "-nostdlib+", "-nowarn:0169,0414,0649,0067",
         "-define:" + defines]
lines += ['-r:"%s"' % r for r in ref_ok]
lines += ['"%s"' % s for s in src_ok + extra]
open(out_rsp, "w", encoding="utf-8").write("\n".join(lines))
print(len(src_ok) + len(extra))
PY
}

# ---- compile both assemblies --------------------------------------------------
status=0
for csproj in Assembly-CSharp.csproj Assembly-CSharp-Editor.csproj; do
  if [ ! -f "$PROJECT_DIR/$csproj" ]; then
    echo "❌ $csproj missing — open the project in Unity on this machine once (and open"
    echo "   any script so the IDE integration regenerates the .csproj files), then re-run."
    status=1
    continue
  fi

  rsp="$WORK/${csproj%.csproj}.rsp"
  count=$(build_rsp "$csproj" "$rsp") || { echo "❌ could not build args for $csproj"; status=1; continue; }

  output=$("$DOTNET" "$CSC" @"$(topath "$rsp")" 2>&1)
  errors=$(echo "$output" | grep -E ": error " | head -25)

  if [ -n "$errors" ]; then
    echo "❌ $csproj"
    echo "$errors"
    status=1
  else
    echo "✅ $csproj ($count sources)"
  fi
done

exit $status
