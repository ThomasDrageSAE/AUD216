    };

    // ---- Directly authored AudioSources --------------------------------------

    /// <summary>
    /// Identifies the Waterfall group below. Not a component type name - there is no
    /// waterfall manager - so it can never collide with one.
    /// </summary>
    private const string WaterfallGroupKey = "#Waterfall";

    /// <summary>
    /// The scanner reads serialized FIELDS, never AudioSource.clip - see the note at the
    /// top of this file. These named AudioSources are the deliberate exception: a handful
    /// of sources whose clip the student drops in DIRECTLY on the AudioSource, with no
    /// manager and no profile in between, and which are assessed all the same. The
    /// waterfall is the one the owner named (2026-09-03).
    ///
    /// Matched on the GameObject's name so the row survives the object being moved in the
    /// hierarchy. Add an entry here when another such source is authored; a source that a
    /// MANAGER fills at runtime must never be listed, or it would be counted twice - once
    /// as the manager's field and once here.
    /// </summary>
    private static readonly DirectAudioSource[] DirectAudioSources =
    {
        new DirectAudioSource(WaterfallGroupKey, "Waterfall", "Waterfall", "Water"),
    };

    /// <summary>One assessed AudioSource that a student fills in by hand.</summary>
    private readonly struct DirectAudioSource
    {
        public DirectAudioSource(string key, string objectName, string groupTitle, string slotLabel)
        {
            Key = key;
            ObjectName = objectName;
            GroupTitle = groupTitle;
            SlotLabel = slotLabel;
        }

        /// <summary>Stands in for a component type name in the ordering lists.</summary>
        public string Key { get; }
        /// <summary>The GameObject to look for, matched case-insensitively.</summary>
        public string ObjectName { get; }
        /// <summary>Section heading.</summary>
        public string GroupTitle { get; }
        /// <summary>The one row inside it.</summary>
        public string SlotLabel { get; }
    }

    /// <summary>
    /// The same walk as <see cref="Scan"/>, handing back a reference per slot instead of a
    /// row - the host, the holding object and field or the list and index - so a tool can
    /// read and write every slot the report lists, and no other. The routing sink receives
    /// every AudioMixerGroup field the walk meets, every scene AudioSource's output group,
    /// and every AudioSource under the registry prefabs and under each extra prefab root
    /// (the enemy and studio prefabs whose sources carry a group; an editor tool supplies
    /// them, because a folder cannot be enumerated at runtime).
    /// </summary>
    public static void WalkSlots(Action<AudioSlotRef> clipSink, Action<AudioRoutingRef> routingSink,
                                 IEnumerable<GameObject> extraPrefabRoots = null)
    {
        // Recording the rows is NOT optional here, and that is exactly why the walk is
        // shared rather than copied: group.Total decides which registry sections survive,
        // which decides which component TYPES the scene pass then skips, so a walk that
        // stopped counting rows would hand the boss's slots back twice. The caller's sink
        // is layered on top of the very RecordRow the report uses, which is what makes
        // "a slot the report lists is a slot a tool can reach, and no other" true by
        // construction rather than by agreement.
        SlotSink sink = (group, slot, clip) =>
        {
            RecordRow(group, slot, clip);
            clipSink?.Invoke(slot);
        };

        WalkSurface(sink, routingSink, extraPrefabRoots);
    }

    public static AudioProgressReport Scan()
    {
        // The same walk WalkSlots runs, with the row recorder as its only sink and no
        // routing sink - so the AudioMixerGroup branch in WalkValue is the plain boundary
        // return it replaced, and the AudioSource sweep never runs. The report is exactly
        // what it always was: same rows, same labels, same order, same export bytes.
        AudioProgressReport report = WalkSurface(RecordRow, null, null);

        FinishGroups(report);
        return report;
    }

    // ---- The one walk ---------------------------------------------------------

    /// <summary>
    /// Receives one clip slot as the walk meets it: the section it belongs to, the
    /// reference to it, and the clip the walk has just read through that reference -
    /// handed over rather than re-read, so a row and its reference cannot disagree.
    /// </summary>
    private delegate void SlotSink(AudioGroupReport group, AudioSlotRef slot, AudioClip clip);

    /// <summary>What the walk carries down: the report being built, and the two sinks.</summary>
    private sealed class WalkContext
    {
        public AudioProgressReport Report;
        public SlotSink ClipSink;

        /// <summary>
        /// Null for <see cref="Scan"/>. The AudioMixerGroup branch in WalkValue is then
        /// the same boundary return it sits in front of, and nothing about the report
        /// depends on it.
        /// </summary>
        public Action<AudioRoutingRef> RoutingSink;

        /// <summary>One per walk, as Scan's own always were: the cycle guard...</summary>
        public readonly HashSet<object> Visited = new HashSet<object>();
        /// <summary>...and the asset de-duplication (a music state, a listed prefab).</summary>
        public readonly HashSet<UnityEngine.Object> ScannedAssets = new HashSet<UnityEngine.Object>();
    }

    /// <summary>
    /// The UnityEngine.Object that SERIALIZES whatever the walk is looking at, and so how
    /// a write to it has to be persisted. Decided once per entry point and threaded down:
    /// a scene MonoBehaviour is Scene; a component on a registry prefab is Prefab and
    /// carries the prefab root a save needs; a MusicStateDefinition is Asset.
    /// </summary>
    private readonly struct WalkHost
    {
        public readonly UnityEngine.Object Object;
        public readonly AudioHostKind Kind;
        public readonly GameObject PrefabRoot;

        public WalkHost(UnityEngine.Object host, AudioHostKind kind, GameObject prefabRoot)
        {
            Object = host;
            Kind = kind;
            PrefabRoot = prefabRoot;
        }
    }

    /// <summary>
    /// Where a leaf the walk has reached actually LIVES: the object and field holding it,
    /// the list and index holding it, or the AudioSource whose own clip it is. The
    /// IMMEDIATE holder is what a write goes through, which is also what catches a boxed
    /// struct holder rather than swallowing the write - see AudioSlotRef.Set. (Nothing in
    /// this project's audio surface is held by a struct; every profile type is a class.)
    /// </summary>
    private readonly struct SlotLocation
    {
        public readonly object Container;
        public readonly FieldInfo Field;
        public readonly int Index;
        public readonly AudioSource Source;

        private SlotLocation(object container, FieldInfo field, int index, AudioSource source)
        {
            Container = container;
            Field = field;
            Index = index;
            Source = source;
        }

        public static SlotLocation OnField(object container, FieldInfo field) =>
            new SlotLocation(container, field, -1, null);

        public static SlotLocation InList(IList list, int index) =>
            new SlotLocation(list, null, index, null);

        public static SlotLocation OnSource(AudioSource source) =>
            new SlotLocation(null, null, -1, source);
    }

    /// <summary>
    /// Discovery, in the order the report has always used: the registry's prefab-only
    /// components first (the scene pass has to know which types they spoke for), then the
    /// scene behaviours, then the registry sections appended, then the direct
    /// AudioSources. The routing sweep, when there is one, runs last and adds no rows.
    ///
    /// FinishGroups is deliberately not called here. It renames and reorders sections for
    /// display, and a reference carries the name its slot was MET under - the walk's own
    /// name, before disambiguation - which is what AudioSlotRef documents.
    /// </summary>
    private static AudioProgressReport WalkSurface(SlotSink clipSink, Action<AudioRoutingRef> routingSink,
                                                   IEnumerable<GameObject> extraPrefabRoots)
    {
        var report = new AudioProgressReport { ScannedAt = DateTime.Now };
        var context = new WalkContext
        {
            Report = report,
            ClipSink = clipSink,
            RoutingSink = routingSink
        };

        // The prefab-only components come first even though their sections are appended
        // last, because the scene pass has to know which component TYPES the registry
        // has already spoken for before it starts skipping them. Walking rather than
        // merely listing those types is the point: a type the registry contributes NO
        // rows for (ZombieAI sits on the boss prefab and owns no clip slot) must not
        // silence that type's scene instances, and only the walk can tell.
        var registryGroups = new List<AudioGroupReport>();
        var registryTypes = new HashSet<Type>();
        var registryPrefabs = new List<GameObject>();
        CollectRegistryGroups(context, registryGroups, registryTypes, registryPrefabs);

        MonoBehaviour[] behaviours = UnityEngine.Object.FindObjectsByType<MonoBehaviour>(
            FindObjectsInactive.Include, FindObjectsSortMode.None);

        // Stable ordering so the report reads the same every time.
        Array.Sort(behaviours, CompareBehaviours);

        foreach (MonoBehaviour behaviour in behaviours)
        {
            if (behaviour == null) continue;

            Type type = behaviour.GetType();
            if (!IsProjectType(type)) continue;
            if (behaviour is AudioProgressReportUI) continue;

            // Already reported from the prefab: the boss during its wave, the rod after
            // pickup. Without this the same slots would appear twice the moment play
            // spawned one, and the in-game total would disagree with the editor's.
            if (registryTypes.Contains(type)) continue;

            var group = new AudioGroupReport
            {
                Name = GroupTitle(type),
                TypeName = type.Name,
                ObjectName = behaviour.gameObject.name
            };
            WalkObject(behaviour, new WalkHost(behaviour, AudioHostKind.Scene, null),
                       group, context, "", 0);

            if (group.Total > 0)
            {
                AddGroup(report, group);
            }
        }

        // After the scene behaviours, so the prefab sections read below the components
        // that are really there.
        foreach (AudioGroupReport registryGroup in registryGroups)
        {
            AddGroup(report, registryGroup);
        }

        AddDirectAudioSourceGroups(context);

        if (routingSink != null) SweepAudioSourceRouting(context, registryPrefabs, extraPrefabRoots);

        return report;
    }

    /// <summary>
    /// Adds a section per <see cref="DirectAudioSources"/> entry found in the scene. These
    /// are the only places the report looks at an AudioSource's own clip; everything else
    /// is a serialized field on a project component.
    /// </summary>
    private static void AddDirectAudioSourceGroups(WalkContext context)
    {
        AudioSource[] sources = UnityEngine.Object.FindObjectsByType<AudioSource>(
            FindObjectsInactive.Include, FindObjectsSortMode.None);

        foreach (DirectAudioSource wanted in DirectAudioSources)
        {
            foreach (AudioSource source in sources)
            {
                if (source == null) continue;
                if (!string.Equals(source.gameObject.name, wanted.ObjectName,
                                   StringComparison.OrdinalIgnoreCase)) continue;

                var group = new AudioGroupReport
                {
                    Name = wanted.GroupTitle,
                    TypeName = wanted.Key,
                    ObjectName = source.gameObject.name
                };

                // The slot label holds no path separator, so TrimCategory hands it back
                // unchanged: row and reference both read "Water".
                RecordSlot(group, context, new WalkHost(source, AudioHostKind.Scene, null),
                           SlotLocation.OnSource(source), wanted.SlotLabel, source.clip);
                AddGroup(context.Report, group);
                break;      // the first match wins; a duplicate name is an authoring mistake
            }
        }
    }

    // ---- Routing --------------------------------------------------------------

    /// <summary>
    /// The AudioSources' own output groups - the half of the routing surface no field walk
    /// can reach, because an AudioSource reference is precisely where WalkValue stops.
    ///
    /// Every AudioSource in the scene, then every AudioSource under each registry prefab
    /// and under each extra root the caller named. Both passes are ordered by hierarchy
    /// path and then by the source's index among its GameObject's AudioSources - a pair
    /// unique to each source, so the order is fixed however Unity returns them. A source
    /// is emitted once: a prefab the registry lists AND the caller hands in as an extra
    /// root is the ordinary case, not a mistake.
    /// </summary>
    private static void SweepAudioSourceRouting(WalkContext context, List<GameObject> registryPrefabs,
                                                IEnumerable<GameObject> extraPrefabRoots)
    {
        var seenSources = new HashSet<AudioSource>();

        AudioSource[] sceneSources = UnityEngine.Object.FindObjectsByType<AudioSource>(
            FindObjectsInactive.Include, FindObjectsSortMode.None);

        foreach (RoutedSource entry in OrderSources(sceneSources, null))
        {
            if (!seenSources.Add(entry.Source)) continue;
            context.RoutingSink(SourceRouting(entry, AudioHostKind.Scene, null));
        }

        var seenRoots = new HashSet<GameObject>();
        foreach (GameObject root in EnumeratePrefabRoots(registryPrefabs, extraPrefabRoots))
        {
            if (root == null || !seenRoots.Add(root)) continue;

            AudioSource[] prefabSources = root.GetComponentsInChildren<AudioSource>(true);
            foreach (RoutedSource entry in OrderSources(prefabSources, root))
            {
                if (!seenSources.Add(entry.Source)) continue;
                context.RoutingSink(SourceRouting(entry, AudioHostKind.Prefab, root));
            }
        }
    }

    private static IEnumerable<GameObject> EnumeratePrefabRoots(List<GameObject> registryPrefabs,
                                                                IEnumerable<GameObject> extraPrefabRoots)
    {
        foreach (GameObject prefab in registryPrefabs) yield return prefab;

        if (extraPrefabRoots == null) yield break;
        foreach (GameObject extra in extraPrefabRoots) yield return extra;
    }

    /// <summary>One AudioSource and the two things that fix its place in the list.</summary>
    private readonly struct RoutedSource
    {
        public readonly AudioSource Source;
        /// <summary>The scene hierarchy path, or the prefab's name and the path inside it.</summary>
        public readonly string Path;
        /// <summary>Which AudioSource this is on its GameObject; a source is not always alone.</summary>
        public readonly int Index;

        public RoutedSource(AudioSource source, string path, int index)
        {
            Source = source;
            Path = path;
            Index = index;
        }
    }

    private static List<RoutedSource> OrderSources(AudioSource[] sources, GameObject prefabRoot)
    {
        var ordered = new List<RoutedSource>(sources.Length);
        foreach (AudioSource source in sources)
        {
            if (source == null) continue;

            string path = prefabRoot == null
                ? HierarchyPath(source.transform)
                : PrefabPath(prefabRoot, source.transform);
            ordered.Add(new RoutedSource(source, path, ComponentIndex(source)));
        }

        ordered.Sort((a, b) =>
        {
            int byPath = string.CompareOrdinal(a.Path, b.Path);
            if (byPath != 0) return byPath;
            // Three mushrooms named "Mushroom" under one parent share a path; FindObjectsByType
            // returns them in no fixed order, so the sibling indices break the tie the same
            // way every run (the self-test compares two routing lists line by line).
            int bySiblings = string.CompareOrdinal(SiblingKey(a.Source.transform), SiblingKey(b.Source.transform));
            return bySiblings != 0 ? bySiblings : a.Index.CompareTo(b.Index);
        });
        return ordered;
    }

    /// <summary>Sibling indices root-to-leaf, zero-padded, so same-named objects under one parent still sort stably.</summary>
    private static string SiblingKey(Transform transform)
    {
        var builder = new StringBuilder();
        for (Transform current = transform; current != null; current = current.parent)
        {
            builder.Insert(0, current.GetSiblingIndex().ToString("D5") + "/");
        }
        return builder.ToString();
    }

    private static AudioRoutingRef SourceRouting(RoutedSource entry, AudioHostKind kind, GameObject prefabRoot)
    {
        return new AudioRoutingRef
        {
            Host = entry.Source,
            PrefabRoot = prefabRoot,
            HostKind = kind,
            GroupName = entry.Path,
            TypeName = nameof(AudioSource),
            ObjectName = entry.Source.gameObject.name,
            Label = "Output",
            Source = entry.Source
        };
    }

    private static int ComponentIndex(AudioSource source)
    {
        AudioSource[] siblings = source.GetComponents<AudioSource>();
        for (int i = 0; i < siblings.Length; i++)
        {
            if (ReferenceEquals(siblings[i], source)) return i;
        }
        return 0;
    }

    /// <summary>"Audio Managers/Waterfall": every ancestor, root first.</summary>
    private static string HierarchyPath(Transform transform)
    {
        var builder = new StringBuilder(transform.name);
        for (Transform parent = transform.parent; parent != null; parent = parent.parent)
        {
            builder.Insert(0, '/').Insert(0, parent.name);
        }
        return builder.ToString();
    }

    /// <summary>The prefab's name, then the path inside it: "BossZombie/Audio/Voice".</summary>
    private static string PrefabPath(GameObject root, Transform transform)
    {
        Transform rootTransform = root.transform;
        if (transform == rootTransform) return root.name;

        var builder = new StringBuilder(transform.name);
        for (Transform parent = transform.parent; parent != null; parent = parent.parent)
        {
            if (parent == rootTransform) return root.name + "/" + builder;
            builder.Insert(0, '/').Insert(0, parent.name);
        }

        // Not under that root after all - the caller handed in something unexpected. The
        // absolute path is still a stable, readable key.
        return HierarchyPath(transform);
    }

    /// <summary>Stable order for a component list: by type name, then by object name.</summary>
    private static int CompareBehaviours(MonoBehaviour a, MonoBehaviour b)
    {
        if (a == null || b == null) return 0;
        int byType = string.CompareOrdinal(a.GetType().Name, b.GetType().Name);
        return byType != 0 ? byType : string.CompareOrdinal(a.name, b.name);
    }

    /// <summary>
    /// Walks the prefabs listed on the scene's <see cref="AssessedPrefabRegistry"/>, if
    /// there is one, and collects a section per component that owns clip slots. This is
    /// the only place the scanner crosses the Unity-object boundary WalkValue draws, and
    /// it crosses it only into prefabs a human dropped into that list.
    ///
    /// Follows the MusicStateDefinition precedent: the context's scanned-asset set
    /// de-duplicates (the same prefab listed twice is walked once) and a section is kept
    /// only when it holds at least one row. Sections are collected rather than added so
    /// the caller can place them after the scene's, the types are reported back so the
    /// caller can skip a scene instance of anything already counted here, and the roots
    /// themselves come back for the routing sweep, which needs their AudioSources.
    /// </summary>
    private static void CollectRegistryGroups(WalkContext context, List<AudioGroupReport> groups,
                                              HashSet<Type> types, List<GameObject> prefabRoots)
    {
        var registry = UnityEngine.Object.FindFirstObjectByType<AssessedPrefabRegistry>(
            FindObjectsInactive.Include);
        if (registry == null || registry.prefabs == null) return;

        foreach (GameObject prefab in registry.prefabs)
        {
            if (prefab == null) continue;
            if (!context.ScannedAssets.Add(prefab)) continue;   // the same prefab listed twice
            prefabRoots.Add(prefab);

            MonoBehaviour[] components = prefab.GetComponentsInChildren<MonoBehaviour>(true);
            Array.Sort(components, CompareBehaviours);

            foreach (MonoBehaviour component in components)
            {
                if (component == null) continue;        // a missing script on the prefab
                if (component is AudioProgressReportUI) continue;

                Type type = component.GetType();
                if (!IsProjectType(type)) continue;

                // Named the way a scene section is - the type in words - with the
                // prefab's name standing where a scene section carries the GameObject's,
                // so the duplicate-name suffix in FinishGroups still works if a type ever
                // turns up on two listed prefabs.
                var group = new AudioGroupReport
                {
                    Name = GroupTitle(type),
                    TypeName = type.Name,
                    ObjectName = prefab.name
                };
                WalkObject(component, new WalkHost(component, AudioHostKind.Prefab, prefab),
                           group, context, "", 0);

                if (group.Total > 0)
                {
                    groups.Add(group);
                    types.Add(type);
                }
            }
        }
    }

    /// <summary>
    /// The heading a group shows: the component's name split into words ("Ambience
    /// Manager", not "AmbienceManager"), and plain "Footsteps" for the footstep manager.
    /// </summary>
    private static string GroupTitle(Type type)
    {
        return type.Name == FootstepsTypeName ? FootstepsTitle : Prettify(type.Name);
    }

    /// <summary>
    /// Ordering and disambiguation, once every group is in. The GameObject name used to
    /// be part of every heading ("AmbienceManager  (Audio Managers)"); it only earns its
    /// place when the same component type occurs more than once in the scene (the bird
    /// and frog RandomSoundSpawners), so it is appended for those alone. Footsteps then
    /// moves to the top - students work on it first, and a ticked-off first section is a
    /// good start to the list.
    /// </summary>
    private static void FinishGroups(AudioProgressReport report)
    {
        var perType = new Dictionary<string, int>();
        foreach (AudioGroupReport group in report.Groups)
        {
            if (group.TypeName == null) continue;
            perType.TryGetValue(group.TypeName, out int count);
            perType[group.TypeName] = count + 1;
        }

        foreach (AudioGroupReport group in report.Groups)
        {
            if (group.TypeName != null && perType[group.TypeName] > 1)
            {
                string suffix = DisambiguationName(group);
                if (!string.IsNullOrEmpty(suffix)) group.Name = $"{group.Name}  ({suffix})";
            }
        }

        // Explicit order for the sections the owner placed by hand, alphabetical for the
        // rest. List.Sort is unstable, so the walk's own order is the tie-break, captured
        // up front rather than looked up per comparison.
        int total = report.Groups.Count;
        var order = new KeyValuePair<int, int>[total];      // rank, original index
        var groups = new AudioGroupReport[total];

        for (int i = 0; i < total; i++)
        {
            groups[i] = report.Groups[i];
            order[i] = new KeyValuePair<int, int>(GroupRank(groups[i]), i);
        }

        Array.Sort(order, (a, b) =>
        {
            int byRank = a.Key.CompareTo(b.Key);
            return byRank != 0 ? byRank : a.Value.CompareTo(b.Value);
        });

        report.Groups.Clear();
        foreach (KeyValuePair<int, int> slot in order)
        {
            report.Groups.Add(groups[slot.Value]);
        }
    }

    /// <summary>
    /// What the GameObject's name contributes to a repeated section's heading: the part
    /// of it the heading does not already say. "Birds - Random Sound Spawner (6)" beside
    /// a heading that already reads "Random Sound Spawner" said the type twice and threw
    /// in Unity's duplicate counter; the one word the reader needs is "Birds". Falls back
    /// to the whole name when the strip leaves nothing, so two sections never read alike.
    /// Display only - the GameObject keeps its name.
    /// </summary>
    private static string DisambiguationName(AudioGroupReport group)
    {
        string name = group.ObjectName;
        if (string.IsNullOrEmpty(name)) return null;

        string trimmed = StripDuplicateCounter(name);
        trimmed = RemoveWords(trimmed, Prettify(group.TypeName));
        trimmed = RemoveWords(trimmed, group.TypeName);
        trimmed = trimmed.Trim(' ', '-', '_', ':');     // separators the removal left behind

        return trimmed.Length > 0 ? trimmed : name;
    }

    /// <summary>
    /// Drops the " (2)" Unity appends when an object is duplicated. Only digits inside
    /// the brackets count, so an authored "Chimes (far bank)" keeps its parenthesis.
    /// </summary>
    private static string StripDuplicateCounter(string name)
    {
        if (!name.EndsWith(")", StringComparison.Ordinal)) return name;

        int open = name.LastIndexOf(" (", StringComparison.Ordinal);
        if (open < 0) return name;

        int first = open + 2;
        int last = name.Length - 1;                     // the ')'
        if (first >= last) return name;                 // "Foo ()"

        for (int i = first; i < last; i++)
        {
            if (!char.IsDigit(name[i])) return name;
        }
        return name.Substring(0, open);
    }

    /// <summary>Removes the first occurrence of a phrase, case-insensitively; the text unchanged when it is absent.</summary>
    private static string RemoveWords(string text, string phrase)
    {
        if (string.IsNullOrEmpty(text) || string.IsNullOrEmpty(phrase)) return text;

        int at = text.IndexOf(phrase, StringComparison.OrdinalIgnoreCase);
        if (at < 0) return text;

        return text.Substring(0, at) + text.Substring(at + phrase.Length);
    }

    /// <summary>
    /// Where a section sits: negative for the hand-placed ones at the top, 0 for the
    /// alphabetical middle, positive for the hand-placed ones at the bottom.
    /// </summary>
    private static int GroupRank(AudioGroupReport group)
    {
        if (group.TypeName == null) return 0;       // a music asset: leave it where it fell

        for (int i = 0; i < GroupsFirst.Length; i++)
        {
            if (group.TypeName == GroupsFirst[i]) return i - GroupsFirst.Length;
        }

        for (int i = 0; i < GroupsLast.Length; i++)
        {
            if (group.TypeName == GroupsLast[i]) return i + 1;
        }

        return 0;
    }

    private static bool IsProjectType(Type type)
    {
        string ns = type.Namespace;
        if (string.IsNullOrEmpty(ns)) return true;

        foreach (string projectNs in ProjectNamespaces)
        {
            if (ns == projectNs || ns.StartsWith(projectNs + ".", StringComparison.Ordinal)) return true;
        }
        return false;
    }

    private static void AddGroup(AudioProgressReport report, AudioGroupReport group)
    {
        report.Groups.Add(group);
        report.Implemented += group.Implemented;
        report.PlaceholderCount += group.PlaceholderCount;
        report.EmptyCount += group.EmptyCount;
    }

    // ---- Reflection walk ------------------------------------------------------

    private static void WalkObject(object instance, WalkHost host, AudioGroupReport group,
                                   WalkContext context, string path, int depth)
    {
        if (instance == null || depth > MaxDepth) return;
        if (!instance.GetType().IsValueType && !context.Visited.Add(instance)) return;

        // A profile may declare some of its own slots irrelevant to this instance. The
        // filter gates the FIELD, so it hides that field's routing reference exactly as it
        // hides the clip slots beneath it. In practice no routing reference changes hands
        // because of it: every implementation answers true for a name it does not know.
        var slotFilter = instance as IAudioSlotFilter;

        foreach (FieldInfo field in EnumerateSerializedFields(instance.GetType()))
        {
            if (slotFilter != null && !slotFilter.IsAudioSlotRelevant(field.Name)) continue;

            object value;
            try { value = field.GetValue(instance); }
            catch { continue; }

            // A clip slot's label loses its "Sound"/"Clip"/"Audio" tail, and vanishes
            // outright when that was the whole of it (a field named literally "clip").
            string fieldLabel = ClipFieldLabel(field, !string.IsNullOrEmpty(path));
            string childPath = string.IsNullOrEmpty(fieldLabel)
                ? path
                : string.IsNullOrEmpty(path) ? fieldLabel : path + PathSeparator + fieldLabel;

            WalkValue(value, field.FieldType, SlotLocation.OnField(instance, field), host,
                      group, context, childPath, depth);
        }
    }

    private static void WalkValue(object value, Type declaredType, SlotLocation where, WalkHost host,
                                  AudioGroupReport group, WalkContext context, string path, int depth)
    {
        // AudioClip leaf - the thing being counted. The declared type matters, not the
        // value: an EMPTY clip slot is precisely a null of declared type AudioClip.
        if (typeof(AudioClip).IsAssignableFrom(declaredType))
        {
            RecordSlot(group, context, host, where, path, value as AudioClip);
            return;
        }

        // Music content assets get their own group per asset. The definition becomes the
        // host from here down: a write inside it is an asset write, not a scene one.
        if (typeof(MusicStateDefinition).IsAssignableFrom(declaredType))
        {
            var definition = value as MusicStateDefinition;
            if (definition != null && context.ScannedAssets.Add(definition))
            {
                var assetGroup = new AudioGroupReport { Name = $"Music State: {definition.name}" };
                WalkObject(definition, new WalkHost(definition, AudioHostKind.Asset, null),
                           assetGroup, context, "", depth + 1);
                if (assetGroup.Total > 0) AddGroup(context.Report, assetGroup);
            }
            return;
        }

        // The routing half of the surface, caught on its way to the boundary below: an
        // AudioMixerGroup IS a Unity object, so without this branch it would simply be
        // dropped there. Without a routing sink - Scan - it is dropped just the same.
        if (typeof(AudioMixerGroup).IsAssignableFrom(declaredType))
        {
            RecordRouting(group, context, host, where, path);
            return;
        }

        // Any other Unity object reference is a boundary - following materials, prefabs
        // or textures would drag the whole asset graph into the report.
        if (typeof(UnityEngine.Object).IsAssignableFrom(declaredType)) return;

        // Arrays and lists: recurse per element, labelling by the element's own name
        // field when it has one (profile entries almost always do).
        if (value is IList list)
        {
            Type elementType = GetElementType(declaredType);
            for (int i = 0; i < list.Count; i++)
            {
                object element = list[i];
                string elementLabel = DescribeElement(element, i);
                WalkValue(element, element?.GetType() ?? elementType, SlotLocation.InList(list, i),
                    host, group, context, path + PathSeparator + elementLabel, depth + 1);
            }
            return;
        }

        // Plain serializable class: recurse into its fields.
        if (value != null && IsSerializableClass(value.GetType()))
        {
            WalkObject(value, host, group, context, path, depth + 1);
        }
    }

    /// <summary>
    /// Builds the reference to one clip slot and hands it to the sink. Its Label is
    /// TrimCategory(path), computed once here, so the row the sink records and the
    /// reference it is handed carry the very same string - not two that agree by luck.
    /// </summary>
    private static void RecordSlot(AudioGroupReport group, WalkContext context, WalkHost host,
                                   SlotLocation where, string path, AudioClip clip)
    {
        var slot = new AudioSlotRef
        {
            Host = host.Object,
            PrefabRoot = host.PrefabRoot,
            HostKind = host.Kind,
            GroupName = group.Name,
            TypeName = group.TypeName,
            ObjectName = group.ObjectName,
            Label = TrimCategory(path),
            Container = where.Container,
            Field = where.Field,
            Index = where.Index,
            Source = where.Source
        };

        context.ClipSink(group, slot, clip);
    }

    /// <summary>
    /// The row the report prints, unchanged from when the walk was Scan's alone. The clip
    /// is the one the walk read through this very reference, so no second read can drift.
    /// </summary>
    private static void RecordRow(AudioGroupReport group, AudioSlotRef slot, AudioClip clip)
    {
        var row = new AudioSlotInfo { Label = slot.Label };

        if (clip == null)
        {
            row.State = AudioSlotState.Empty;
            row.ClipName = "-";
            group.EmptyCount++;
        }
        else
        {
            row.ClipName = clip.name;
            row.State = ClassifyClip(clip);
            if (row.State == AudioSlotState.Implemented) group.Implemented++;
            else group.PlaceholderCount++;
        }

        group.Slots.Add(row);
    }

    /// <summary>
    /// One AudioMixerGroup field. Its Label is the FULL field path, untrimmed: a routing
    /// reference is a tool's key rather than a report row, and "Enemy Profiles ▸ Butcher ▸
    /// Vocalisation Mixer Group" says where it lives without the report open beside it.
    /// </summary>
    private static void RecordRouting(AudioGroupReport group, WalkContext context, WalkHost host,
                                      SlotLocation where, string path)
    {
        if (context.RoutingSink == null) return;

        context.RoutingSink(new AudioRoutingRef
        {
            Host = host.Object,
            PrefabRoot = host.PrefabRoot,
            HostKind = host.Kind,
            GroupName = group.Name,
            TypeName = group.TypeName,
            ObjectName = group.ObjectName,
            Label = path,
            Container = where.Container,
            Field = where.Field,
            Index = where.Index
        });
    }

    /// <summary>
    /// Drops the leading category segment - the profile-list field the slot sits in
    /// ("Enemy Profiles", "Surface Profiles", "Impact Effects"...) - once a profile name
    /// follows it to carry the meaning: "Enemy Profiles ▸ Zombie ▸ Attack Sounds ▸ [0]"
    /// reads as "Zombie ▸ Attack Sounds ▸ [0]". The category stays when nothing better
    /// follows it: a two-segment "Dawn Chorus Clips ▸ [0]" would otherwise be "[0]", and
    /// an unnamed entry such as "Pickup Sounds ▸ [2] ▸ Clip" would lose its only noun.
    /// </summary>
    private static string TrimCategory(string path)
    {
        int first = path.IndexOf(PathSeparator, StringComparison.Ordinal);
        if (first < 0) return path;

        int second = path.IndexOf(PathSeparator, first + PathSeparator.Length, StringComparison.Ordinal);
        if (second < 0) return path;

        string next = path.Substring(first + PathSeparator.Length);
        if (next.StartsWith("[", StringComparison.Ordinal)) return path;

        return next;
    }

    /// <summary>
    /// BEEP (Placeholder) for a beep - "beep" in the name covers the shipped "Beep to
    /// replace" clips and any student copies - or a generated music test stem; REPLACE
    /// (Demo) for any other clip from the Demo sounds folder, found by asset path in the
    /// editor and by "demo" in the name in a build; Implemented for everything else.
    /// </summary>
    public static AudioSlotState ClassifyClip(AudioClip clip)
    {
        if (clip == null) return AudioSlotState.Empty;

        if (clip.name.IndexOf("beep", StringComparison.OrdinalIgnoreCase) >= 0) return AudioSlotState.Placeholder;
        if (TestStemName.IsMatch(clip.name)) return AudioSlotState.Placeholder;

#if UNITY_EDITOR
        string assetPath = UnityEditor.AssetDatabase.GetAssetPath(clip);
        if (!string.IsNullOrEmpty(assetPath))
        {
            if (assetPath.StartsWith(TestStemsFolder, StringComparison.OrdinalIgnoreCase)) return AudioSlotState.Placeholder;
            if (assetPath.StartsWith(DemoSoundsFolder, StringComparison.OrdinalIgnoreCase)) return AudioSlotState.Demo;
        }
#endif
        if (clip.name.IndexOf("demo", StringComparison.OrdinalIgnoreCase) >= 0) return AudioSlotState.Demo;

        return AudioSlotState.Implemented;
    }

    /// <summary>True for anything that still counts as not done: a beep, a test stem or a demo clip.</summary>
    public static bool IsPlaceholderClip(AudioClip clip)
    {
        AudioSlotState state = ClassifyClip(clip);
        return state == AudioSlotState.Placeholder || state == AudioSlotState.Demo;
    }

    // ---- Reflection helpers ---------------------------------------------------

    private static IEnumerable<FieldInfo> EnumerateSerializedFields(Type type)
    {
        // Walk the hierarchy explicitly: GetFields never returns private fields
        // declared on base classes, and profile classes do inherit occasionally.
        for (Type current = type; current != null && current != typeof(MonoBehaviour)
             && current != typeof(ScriptableObject) && current != typeof(object); current = current.BaseType)
        {
            FieldInfo[] fields = current.GetFields(
                BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.DeclaredOnly);

            foreach (FieldInfo field in fields)
            {
                if (field.IsStatic) continue;
                if (field.IsDefined(typeof(NonSerializedAttribute), false)) continue;

                bool serialized = field.IsPublic || field.IsDefined(typeof(SerializeField), false);
                if (!serialized) continue;

                yield return field;
            }
        }
    }

    private static bool IsSerializableClass(Type type)
    {
        if (type.IsPrimitive || type.IsEnum || type == typeof(string)) return false;
        if (typeof(UnityEngine.Object).IsAssignableFrom(type)) return false;
        if (typeof(Delegate).IsAssignableFrom(type)) return false;
        return type.IsDefined(typeof(SerializableAttribute), false);
    }

    private static Type GetElementType(Type listType)
    {
        if (listType.IsArray) return listType.GetElementType();
        if (listType.IsGenericType) return listType.GetGenericArguments()[0];
        return typeof(object);
    }

    /// <summary>
    /// Elements of profile arrays are labelled by their own identifying field when one
    /// exists ("Zombie", "Grass"...) so the report reads like the inspector does, falling
    /// back to the index. A name wins; failing that a type, tag or id field - the surface
    /// profiles say "surfaceType" and the impact effects "surfaceTag", and both used to
    /// list as [0], [1]... An enum id counts only once it has been assigned.
    /// </summary>
    private static string DescribeElement(object element, int index)
    {
        if (element != null && IsSerializableClass(element.GetType()))
        {
            string best = null;
            int bestRank = int.MaxValue;

            foreach (FieldInfo field in EnumerateSerializedFields(element.GetType()))
            {
                int rank = IdentifierRank(field.Name);
                if (rank < 0 || rank >= bestRank) continue;

                string text = null;
                if (field.FieldType == typeof(string))
                {
                    text = field.GetValue(element) as string;
                }
                else if (field.FieldType.IsEnum)
                {
                    string raw = field.GetValue(element)?.ToString();
                    if (!string.IsNullOrEmpty(raw) && raw != "Unassigned" && raw != "None") text = Prettify(raw);
                }

                if (!string.IsNullOrEmpty(text))
                {
                    best = text;
                    bestRank = rank;
                }
            }

            if (best != null) return Capitalise(best);
        }
        return $"[{index}]";
    }

    /// <summary>
    /// A profile entry's own name, with a capital first letter. The footstep surfaces are
    /// authored lower-case ("wood", "grass") because the string is a lookup key matched
    /// case-insensitively; the report is prose, so it reads "Wood" (owner, 2026-09-03).
    /// Display only - the authored string is untouched, and the lookup still matches.
    /// </summary>
    private static string Capitalise(string label)
    {
        if (string.IsNullOrEmpty(label)) return label;
        if (char.IsUpper(label[0])) return label;

        return char.ToUpperInvariant(label[0]) + label.Substring(1);
    }

    /// <summary>Which fields may name a profile entry, most specific first; -1 for none.</summary>
    private static int IdentifierRank(string fieldName)
    {
        if (fieldName.IndexOf("name", StringComparison.OrdinalIgnoreCase) >= 0) return 0;
        if (fieldName.IndexOf("type", StringComparison.OrdinalIgnoreCase) >= 0) return 1;
        if (fieldName.IndexOf("tag", StringComparison.OrdinalIgnoreCase) >= 0) return 2;
        if (fieldName.EndsWith("Id", StringComparison.Ordinal) || fieldName.EndsWith("ID", StringComparison.Ordinal)) return 3;
        return -1;
    }

    private static string Prettify(string fieldName)
    {
        if (string.IsNullOrEmpty(fieldName)) return fieldName;

        // m_FooBar / fooBar / UIAudioManager -> "Foo Bar" / "Foo Bar" / "UI Audio Manager":
        // a space goes before a capital that follows a non-capital, and before the last
        // capital of a run when a lower-case letter follows it (the end of an acronym).
        string trimmed = fieldName.StartsWith("m_", StringComparison.Ordinal) ? fieldName.Substring(2) : fieldName;
        var builder = new StringBuilder(trimmed.Length + 4);
        for (int i = 0; i < trimmed.Length; i++)
        {
            char c = trimmed[i];
            if (i > 0 && char.IsUpper(c))
            {
                bool afterNonCapital = !char.IsUpper(trimmed[i - 1]);
                bool endsAcronym = i + 1 < trimmed.Length && char.IsLower(trimmed[i + 1]);
                if (afterNonCapital || endsAcronym) builder.Append(' ');
            }
            builder.Append(i == 0 ? char.ToUpperInvariant(c) : c);
        }
        return builder.ToString();
    }

