    /// <summary>
    /// Trailing words a clip slot's label does not need, longest pair first. "Loop",
    /// "Chime" and "Stinger" are deliberately absent: a loop, a chime and a stinger say
    /// something about the sound that the reader cannot infer from the row.
    /// </summary>
    private static readonly string[] ClipLabelTails =
        { "Audio Clip", "Sound", "Sounds", "Clip", "Clips", "Audio" };

    /// <summary>
    /// The path segment a field contributes to a slot label. Prettified as ever, then -
    /// for a field the walk can reach clips through - stripped of one trailing
    /// "Sound(s) / Clip(s) / Audio" and put through <see cref="ClipLabelOverrides"/>:
    /// "Footstep Sounds" reads as "Footsteps", "River Audio Clip" as "River",
    /// "Left Speaker Audio" as "Left Speaker".
    ///
    /// Returns null when the segment should disappear altogether, which is what a field
    /// literally named "clip" leaves behind: "Chest Pickup Sound ▸ Clip" becomes
    /// "Chest Pickup" and "Pickup Sounds ▸ [0] ▸ Clip" becomes
    /// "Pickups ▸ [0]". A slot with no parent path keeps its plain label instead,
    /// rather than ending up with no label at all.
    /// </summary>
    private static string ClipFieldLabel(FieldInfo field, bool hasParentPath)
    {
        string prettified = Prettify(field.Name);
        if (!IsClipBearingType(field.FieldType, 0)) return prettified;

        // The override is the final word: it replaces whatever the strip would produce.
        if (ClipLabelOverrides.TryGetValue(field.Name, out string overridden)) return overridden;

        string stripped = null;
        foreach (string tail in ClipLabelTails)
        {
            stripped = StripTrailingWord(prettified, tail);
            if (stripped != null) break;
        }

        if (stripped == null) return prettified;
        if (stripped.Length > 0) return stripped;
        return hasParentPath ? null : prettified;
    }

    /// <summary>
    /// The label without a trailing whole word: "" when the word was the whole label,
    /// null when the label does not end in that word. Whole word, so "Sizzle" keeps its
    /// ending and only " Sound" style tails come off.
    /// </summary>
    private static string StripTrailingWord(string label, string word)
    {
        if (!label.EndsWith(word, StringComparison.Ordinal)) return null;

        int cut = label.Length - word.Length;
        if (cut > 0 && label[cut - 1] != ' ') return null;

        return label.Substring(0, cut).TrimEnd();
    }

    /// <summary>
    /// True for a field the walk can reach an AudioClip through: a clip, an array or list
    /// of clips, or a [Serializable] profile class holding either (PickupSound holds one
    /// bare "clip", so "Chest Pickup Sound" is as much a clip slot's name as the clip
    /// field is). Everything else keeps its plain prettified name - a field that only
    /// groups profiles ("Surface Profiles", "Sound Profiles") is not a clip slot, and
    /// neither are the name/enum segments DescribeElement produces.
    /// </summary>
    private static bool IsClipBearingType(Type type, int depth)
    {
        if (type == null || depth > 4) return false;
        if (typeof(AudioClip).IsAssignableFrom(type)) return true;

        // Same boundary WalkValue draws: other Unity object references are not followed.
        if (typeof(UnityEngine.Object).IsAssignableFrom(type)) return false;

        if (type.IsArray || (type.IsGenericType && typeof(IList).IsAssignableFrom(type)))
        {
            return IsClipBearingType(GetElementType(type), depth);
        }

        if (!IsSerializableClass(type)) return false;

        foreach (FieldInfo nested in EnumerateSerializedFields(type))
        {
            if (IsClipBearingType(nested.FieldType, depth + 1)) return true;
        }
        return false;
    }

    // ---- Export ---------------------------------------------------------------

    public static string BuildExportText(AudioProgressReport report)
    {
        var text = new StringBuilder();
        text.AppendLine("AUDIO IMPLEMENTATION PROGRESS");
        text.AppendLine($"Scene: {UnityEngine.SceneManagement.SceneManager.GetActiveScene().name}");
        text.AppendLine($"Scanned: {report.ScannedAt:yyyy-MM-dd HH:mm}");
        text.AppendLine();
        text.AppendLine($"OVERALL: {report.Implemented}/{report.Total} implemented " +
                        $"({report.Completion:P0})  |  MISSING: {report.Missing}");
        text.AppendLine(new string('=', 72));

        foreach (AudioGroupReport group in report.Groups)
        {
            text.AppendLine();
            text.AppendLine($"{group.Name}  -  {group.Implemented}/{group.Total} ({group.Completion:P0})");
            foreach (AudioSlotInfo slot in group.Slots)
            {
                // One word for everything not done. Which KIND of not-done - empty, a
                // beep, a demo clip - is the scanner's business, not the student's.
                string marker = slot.State == AudioSlotState.Implemented ? "[ok]      " : "[MISSING] ";

                // Only an implemented slot names its clip: the placeholders are the same
                // few files over and over, and the label is what the reader needs.
                text.AppendLine(slot.State == AudioSlotState.Implemented
                    ? $"  {marker}{slot.Label}  =  {slot.ClipName}"
                    : $"  {marker}{slot.Label}");
            }
        }

        return text.ToString();
    }

    /// <summary>Writes the report next to the project (editor) or to persistent data (build).</summary>
    public static string ExportToFile(AudioProgressReport report)
    {
        string directory = Application.isEditor
            ? System.IO.Path.Combine(Application.dataPath, "..", "Exports")
            : Application.persistentDataPath;

        System.IO.Directory.CreateDirectory(directory);
        string file = System.IO.Path.Combine(directory,
            $"AudioProgress_{report.ScannedAt:yyyyMMdd_HHmmss}.txt");
        System.IO.File.WriteAllText(file, BuildExportText(report));
        return System.IO.Path.GetFullPath(file);
    }
