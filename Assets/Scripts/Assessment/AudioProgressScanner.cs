/*
 * AudioProgressScanner.cs
 *
 * Purpose: Scans the scene for every serialized AudioClip slot and classifies each as
 * Implemented, Placeholder or Empty - the data behind the student audio-progress report.
 * Used by: AudioProgressReportUI (in-game popup), AudioProgressReportWindow (editor)
 *
 * Assessment context: students receive this level with placeholder audio and their job
 * is to implement the sounds and music. Everything shipped in Assets/Audio/Demo sounds
 * is a placeholder: the beeps ("Beep to replace.wav", "Beep to replace - footsteps.wav")
 * report as BEEP, the other demo clips (walkie-talkie chatter, the demo heartbeat) as
 * REPLACE, and a slot holding nothing as EMPTY. All three count as not done. A clip
 * generated by the music test-stem tool is a BEEP too.
 *
 * Outside the editor asset paths are unavailable, so a build recognises the demo clips
 * by name instead: "beep" or "demo" anywhere in the clip name. Keep one of those words
 * in any new placeholder's file name, or a build will grade it as implemented.
 *
 * Presentation rules (owner, 2026-09-03): headings are the component's name split into
 * words with no GameObject suffix ("Ambience Manager", not "AmbienceManager  (Audio
 * Managers)"), the footstep manager is "Footsteps" and comes first because students
 * start there, placeholder rows show no clip name, and the leading category segment
 * of a label ("Enemy Profiles", "Surface Profiles"...) is dropped once a profile name
 * follows it. Profile entries read with a capital ("Wood", not the authored "wood").
 * Section order is alphabetical apart from the ones the owner placed by hand - see
 * GroupsFirst / GroupsLast - and the Waterfall section is the one place the report reads
 * an AudioSource's own clip; see DirectAudioSources for why. A clip slot's own label also drops a trailing "Sound(s) / Clip(s) /
 * Audio" - the reader knows the report is about sounds - with ClipLabelOverrides for
 * the readings a bare strip gets wrong: a non-noun ("Lands"), a word the profile name
 * in front of it already carries ("Stamina ▸ Stamina Depleted"), or a singular left
 * among plural siblings ("Headshot" beside "Attacks"). All of that is DISPLAY ONLY: no
 * serialized field is renamed, because the field names are the student-facing
 * authoring surface.
 *
 * How it scans: reflection over the serialized fields of scene components, recursively
 * through [Serializable] profile classes and arrays, collecting every AudioClip leaf.
 * It deliberately reads FIELDS, not AudioSource.clip at runtime - managers assign clips
 * to their sources while playing, and reading sources would double-count those and make
 * the in-game and editor reports disagree.
 *
 * Only project code is scanned (types with no namespace, or in the project's own
 * namespaces). Standard Assets / UI-extension components are excluded: their stale
 * audio fields (e.g. the unused footstep clips on FirstPersonController) are not part
 * of the assessment surface.
 *
 * MusicStateDefinition assets referenced by MusicManager are walked too, each as its
 * own group, so layered music stems are graded once students author them.
 *
 * Prefab-only components are the other door through that same boundary. The boss
 * zombie is spawned by its wave and the fishing rod enters the scene on pickup, so a
 * scene walk can never see either, and their clip slots were missing from the report.
 * AssessedPrefabRegistry - a hand-written list of prefab roots on the Audio Managers
 * object - names them; the walk follows each exactly as it follows a scene component.
 * A component TYPE the registry has already spoken for is then skipped when the scene
 * pass meets an instance of it, so the boss counts once in edit mode and still counts
 * once while it is alive: the in-game total and the editor total agree.
 *
 * That one walk also hands back a REFERENCE per slot, through WalkSlots: the host object,
 * and the holding object and field or the list and index - plus one per AudioMixerGroup
 * field it meets and one per AudioSource output group. Scan() is a client of the same
 * walk, so a slot the report lists is a slot a tool can write, and no other. See
 * AudioSlotRef.cs and Documentation/AUDIO_HANDOUT_TASKS.md.
 */

public enum AudioSlotState
{
    // The three not-done states are kept apart here because the validator and the counts
    // use them; every report SHOWS them as one word, MISSING, in red - the owner's call,
    // 2026-09-06. A student is not marked on which kind of not-done a slot is.

    /// <summary>Nothing assigned: the student has to create a sound.</summary>
    Empty,
    /// <summary>A beep or a generated test stem: to be replaced.</summary>
    Placeholder,
    /// <summary>Any other clip from the Demo sounds folder: to be replaced.</summary>
    Demo,
    Implemented
}

public class AudioSlotInfo
{
    public string Label;
    /// <summary>The assigned clip's name. The views only print it for implemented slots.</summary>
    public string ClipName;
    public AudioSlotState State;
}

public class AudioGroupReport
{
    public string Name;
    /// <summary>Component type behind the group (null for a music asset); used to spot duplicates.</summary>
    public string TypeName;
    public string ObjectName;
    public readonly List<AudioSlotInfo> Slots = new List<AudioSlotInfo>();

    public int Implemented;
    public int PlaceholderCount;
    public int EmptyCount;

    public int Total => Slots.Count;
    public float Completion => Total == 0 ? 1f : Implemented / (float)Total;

    /// <summary>Everything a student still has to do. One number, one word (MISSING), since 2026-09-06.</summary>
    public int Missing => Total - Implemented;
}

public class AudioProgressReport
{
    public readonly List<AudioGroupReport> Groups = new List<AudioGroupReport>();
    public DateTime ScannedAt;

    public int Implemented;
    public int PlaceholderCount;
    public int EmptyCount;
    public int Total => Implemented + PlaceholderCount + EmptyCount;
    public float Completion => Total == 0 ? 1f : Implemented / (float)Total;

    /// <summary>Everything a student still has to do, across the level.</summary>
    public int Missing => Total - Implemented;
}

/// <summary>
/// Implemented by a serialized class holding clip slots that do not apply to every
/// instance of it, so the progress report can leave them out rather than counting them
/// as outstanding work. An axe has no magazine: its reload slots are not unfinished,
/// they are not work at all, and a permanently red row trains the reader to ignore red.
/// </summary>
public interface IAudioSlotFilter
{
    /// <summary>
    /// False to hide that field, and anything nested under it, from the report.
    /// Called with the field's real name, not its prettified label.
    /// </summary>
    bool IsAudioSlotRelevant(string fieldName);
}

