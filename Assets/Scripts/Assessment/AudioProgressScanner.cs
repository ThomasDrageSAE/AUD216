    private const string FootstepsTitle = "Footsteps";
    private const string PathSeparator = " ▸ ";

    /// <summary>
    /// Section order the owner asked for (2026-09-03), for the sections whose position is
    /// a teaching decision rather than alphabetical: students work top-down, so footsteps
    /// come first, then the two water sections. Everything not named here keeps its
